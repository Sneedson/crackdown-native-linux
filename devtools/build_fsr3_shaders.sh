#!/bin/bash
# Compiles AMD FidelityFX FSR 3.1's upscaler shaders (the SDK's GLSL, $FFX or ~/src/ref/FidelityFX-SDK at
# tag v1.1.4) to SPIR-V with glslangValidator, as the SDK's own (Windows-only) shader compiler would, and
# writes them as C arrays to $1 (build.sh: build/fsr3/fsr3_spirv.h). runtime/fsr3/fsr3_blobs.cpp hands
# them to the SDK's Vulkan backend.
#
# Optimised (-Os) as AMD builds them, which also drops resources a variant declares but never uses (the
# SDK only knows the used ones by name). Only the variants this game uses are made: colour not HDR, motion vectors at the render size and
# without jitter, depth inverted (fsr3.cpp's context flags). What varies: the reprojection's Lanczos as a
# lookup table (the SDK picks it on cards with 32 and 64 wide waves, AMD's) and sharpening after the
# accumulation. Index: pass (FfxFsr3UpscalerPass order) x variant (bit 0 lookup table, bit 1 sharpening).
set -e
FFX=${FFX:-$HOME/src/ref/FidelityFX-SDK}
OUT=$1
SDK=$FFX/sdk
G=$SDK/include/FidelityFX/gpu
SRC=$SDK/src/backends/vk/shaders/fsr3upscaler
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
PASSES=(prepare_inputs luma_pyramid shading_change_pyramid shading_change prepare_reactivity luma_instability accumulate accumulate rcas debug_view autogen_reactive)
{
    echo "// Generated by devtools/build_fsr3_shaders.sh from the FidelityFX SDK (MIT licence, (C) Advanced Micro Devices, Inc.)."
    echo "#pragma once"
    echo "#include <cstdint>"
    echo "#include <cstddef>"
} > "$TMP/h"
TABLE=""
for p in "${!PASSES[@]}"; do
    name=${PASSES[$p]}
    row=""
    for v in 0 1 2 3; do
        lut=$(( v & 1 )); sharpen=$(( v >> 1 & 1 ))
        spv=$TMP/${name}_$v.spv
        [ -f "$spv" ] || glslangValidator -Os -V --target-env vulkan1.2 -S comp -DFFX_GLSL=1 -DFFX_GPU=1 \
            -DFFX_FSR3UPSCALER_OPTION_UPSAMPLE_SAMPLERS_USE_DATA_HALF=0 -DFFX_FSR3UPSCALER_OPTION_ACCUMULATE_SAMPLERS_USE_DATA_HALF=0 \
            -DFFX_FSR3UPSCALER_OPTION_REPROJECT_SAMPLERS_USE_DATA_HALF=1 -DFFX_FSR3UPSCALER_OPTION_POSTPROCESSLOCKSTATUS_SAMPLERS_USE_DATA_HALF=0 \
            -DFFX_FSR3UPSCALER_OPTION_UPSAMPLE_USE_LANCZOS_TYPE=2 -DFFX_FSR3UPSCALER_OPTION_REPROJECT_USE_LANCZOS_TYPE=$lut \
            -DFFX_FSR3UPSCALER_OPTION_HDR_COLOR_INPUT=0 -DFFX_FSR3UPSCALER_OPTION_LOW_RESOLUTION_MOTION_VECTORS=1 \
            -DFFX_FSR3UPSCALER_OPTION_JITTERED_MOTION_VECTORS=0 -DFFX_FSR3UPSCALER_OPTION_INVERTED_DEPTH=1 \
            -DFFX_FSR3UPSCALER_OPTION_APPLY_SHARPENING=$sharpen -I"$G" -I"$G/fsr3upscaler" \
            "$SRC/ffx_fsr3upscaler_${name}_pass.glsl" -o "$spv" > "$TMP/log" 2>&1 || { cat "$TMP/log" >&2; exit 1; }
        sym=fsr3_spv_${p}_$v
        python3 -I -c '
import struct, sys
d = open(sys.argv[1], "rb").read()
w = struct.unpack("<%dI" % (len(d) // 4), d)
print("static const uint32_t %s[] = {" % sys.argv[2])
for i in range(0, len(w), 12): print("    " + ", ".join("0x%08X" % x for x in w[i:i + 12]) + ",")
print("};")' "$spv" "$sym" >> "$TMP/h"
        row="$row { $sym, sizeof( $sym ) },"
    done
    TABLE="$TABLE    {$row },  // $name"$'\n'
done
{
    echo "struct Fsr3Spirv { const uint32_t *code; size_t bytes; };"
    echo "static const Fsr3Spirv fsr3_spirv[${#PASSES[@]}][4] = {"
    printf '%s' "$TABLE"
    echo "};"
} >> "$TMP/h"
mkdir -p "$(dirname "$OUT")"
mv "$TMP/h" "$OUT"
echo "wrote $OUT"
