# Generates runtime/xui_schema.h from build/xui_classes.txt (CRACKDOWN_XUI_CLASSDUMP=1): the XUI classes'
# property definitions, in the order a .xur's property masks index them.
#   python3 -I devtools/xui_schema_gen.py build/xui_classes.txt > runtime/xui_schema.h
import sys
classes, stack, order = {}, [], []
for line in open(sys.argv[1]):
    if line.startswith('class '):
        p = line.split(); c = {'name': p[1], 'base': p[3] if len(p) > 3 else '', 'defs': []}
        classes[p[1]] = c; order.append(p[1]); stack = [c['defs']]; continue
    ind = (len(line) - len(line.lstrip(' '))) // 2 - 1
    i, name, t, idx = line.split()
    d = {'name': name, 'type': int(t), 'indexed': int(idx), 'sub': []}
    stack = stack[:ind + 1]; stack[ind].append(d); stack.append(d['sub'])
out, n = [], [0]
def emit(defs):
    if not defs: return 'nullptr'
    subs = [emit(d['sub']) for d in defs]
    n[0] += 1; name = 'D%d' % n[0]
    out.append('const XurDef %s[] = { %s };' % (name, ', '.join('{ "%s", %d, %d, %s, %d }' % (d['name'], d['type'], d['indexed'], s, len(d['sub'])) for d, s in zip(defs, subs))))
    return name
rows = []
for cname in sorted(order):
    c = classes[cname]
    rows.append('{ "%s", "%s", %s, %d }' % (cname, c['base'], emit(c['defs']), len(c['defs'])))
print('// Generated by devtools/xui_schema_gen.py from the game\'s XUI class table (CRACKDOWN_XUI_CLASSDUMP=1).')
print('#pragma once')
print('#include "xur.h"')
print('namespace {')
print('\n'.join(out))
print('const XurClass XUR_CLASSES[] = {\n    ' + ',\n    '.join(rows) + ' };')
print('}')
